// side curve as height fraction of the floor to crown span, x fraction of half width
const SIDE = [
  [0.000, null],
  [0.055, 1.010],
  [0.200, 0.930],
  [0.420, 0.995],
  [0.620, 1.000],
  [0.820, 0.982],
  [1.000, 0.930]
];

const r = (v) => Math.round(v * 10000) / 10000;

const path_points = S.map(([z]) => [0, 0, r(z)]);

const loft_profiles = S.map(([z, hw, fw, y0, ys, yc]) => {
  const h = ys - y0;
  const d = ys - yc;
  const half = SIDE.map(([t, xf]) => [xf === null ? fw : Math.max(fw * xf, xf * hw * 0 + xf * hw) , y0 + t * h]);
  half[0][0] = fw;
  half[1][0] = Math.max(fw * 1.01, 0.86 * hw);
  half.push([0.760 * hw, ys - 0.350 * d - 0.004]);
  half.push([0.420 * hw, yc + 0.100 * d]);
  const pts = [[0, y0]];
  for (const p of half) { pts.push(p); }
  pts.push([0, yc]);
  for (let i = half.length - 1; i >= 0; i--) { pts.push([-half[i][0], half[i][1]]); }
  return pts.map(([x, y]) => [r(x), r(y)]);
});

